function syrup(
  slug: string,
  sku: string,
  flavour: string,
  uk: string,
  en: string,
  noteUk: string,
  noteEn: string,
  stocks: readonly [number, number],
  extra: { compareAt1l?: number } = {},
): SeedProduct {
  return coffeeProduct({
    slug,
    sku,
    title: t(`Сироп «${uk}»`, `${en} syrup`),
    description: t(
      `${noteUk} Пляшка 250 мл для проб або 1 л під дозатор-помпу (10 мл за натиск).`,
      `${noteEn} A 250 ml bottle to try it or a 1 l bottle for a pump (10 ml per press).`,
    ),
    type: "syrup_sauce",
    brand: "siropia",
    categories: SYRUPS,
    attributes: { syrup_flavour: flavour, shelf_life_days: 540 },
    options: [["volume", ["250ml", "1l"]]],
    variants: {
      "250ml": v(12900, stocks[0]),
      "1l": v(
        34900,
        stocks[1],
        extra.compareAt1l === undefined ? {} : { compareAtAmount: extra.compareAt1l },
      ),
    },
  });
}

