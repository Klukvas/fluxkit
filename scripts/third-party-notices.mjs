// Generates third-party/THIRD_PARTY_NOTICES.md for runtime dependencies. Ship it with every client delivery.
import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";

const out = execFileSync("pnpm", ["licenses", "list", "--prod", "--json"], {
  encoding: "utf8",
  maxBuffer: 256 * 1024 * 1024,
});
const byLicense = JSON.parse(out);
const rows = [];
for (const [license, entries] of Object.entries(byLicense)) {
  for (const entry of entries) {
    rows.push({
      name: entry.name,
      versions: (entry.versions ?? []).join(", "),
      license,
      homepage: entry.homepage ?? "",
    });
  }
}
if (rows.length === 0) {
  console.error(
    "third-party-notices: no runtime packages found; refusing to write an empty notice file.",
  );
  process.exit(2);
}
rows.sort((a, b) => a.name.localeCompare(b.name));
const lines = [
  "# Third-party notices",
  "",
  "Runtime dependencies bundled or loaded by Fluxkit, with their licenses. Generated by `pnpm notices`.",
  "Packages under LGPL-3.0-or-later (sharp-libvips) are used unmodified as dynamically loaded binaries; CC-BY-4.0 (caniuse-lite) requires attribution.",
  "",
  "| Package | Version | License | Homepage |",
  "|---|---|---|---|",
  ...rows.map((row) => `| ${row.name} | ${row.versions} | ${row.license} | ${row.homepage} |`),
  "",
  "## Vendored code",
  "",
  "Source files of other projects that are part of the repository (not npm packages), with the notice their licence requires.",
  "",
  "### Snowball stemmers (BSD-3-Clause)",
  "",
  "`packages/core/src/search/stemmers/snowball/`: the Ukrainian and English algorithms of Snowball 3.2.0 (https://snowballstem.org) and the TypeScript generated from them.",
  "",
  ...readFileSync("packages/core/src/search/stemmers/snowball/COPYING", "utf8")
    .trimEnd()
    .split("\n")
    .map((line) => (line === "" ? "" : `    ${line}`)),
  "",
];
mkdirSync("third-party", { recursive: true });
writeFileSync("third-party/THIRD_PARTY_NOTICES.md", lines.join("\n"));
console.log(`Wrote third-party/THIRD_PARTY_NOTICES.md (${rows.length} packages)`);
