// Writes a TypeScript module with every Nth "word stem" pair of a snowball-data vocabulary (voc.txt and output.txt of
// https://github.com/snowballstem/snowball-data, BSD-3-Clause, a word frequency list, no running text). The pairs are the
// reference stems that the generated stemmers must reproduce; the full list is checked by hand with verify-vocabulary.mjs.
//
// Usage: node scripts/snowball/make-vocabulary-sample.mjs <voc.txt> <output.txt> <every> <out.ts> <ExportName> "<description>"
import { readFileSync, writeFileSync } from "node:fs";

const [, , vocPath, outputPath, every, outPath, exportName, description] = process.argv;
if (!vocPath || !outputPath || !every || !outPath || !exportName || !description) {
  console.error(
    "usage: node scripts/snowball/make-vocabulary-sample.mjs <voc.txt> <output.txt> <every> <out.ts> <ExportName> <description>",
  );
  process.exit(2);
}
const words = readFileSync(vocPath, "utf8")
  .split("\n")
  .filter((line) => line !== "");
const stems = readFileSync(outputPath, "utf8")
  .split("\n")
  .filter((line) => line !== "");
if (words.length !== stems.length) {
  console.error(`voc has ${words.length} words but output has ${stems.length} stems`);
  process.exit(1);
}
const step = Number(every);
const lines = [];
for (let i = 0; i < words.length; i += step) {
  if (/[\s`$\\]/.test(words[i]) || /[\s`$\\]/.test(stems[i])) {
    console.error(`unsafe line ${i}: ${words[i]} ${stems[i]}`);
    process.exit(1);
  }
  lines.push(`${words[i]} ${stems[i]}`);
}
writeFileSync(
  outPath,
  [
    `// ${description}`,
    `// Every ${step}th pair of ${words.length} (snowball-data, BSD-3-Clause, see snowball/COPYING). Generated by scripts/snowball/make-vocabulary-sample.mjs.`,
    `export const ${exportName} = \`${lines.join("\n")}\n\`;`,
    "",
  ].join("\n"),
);
console.log(`${outPath}: ${lines.length} pairs`);
